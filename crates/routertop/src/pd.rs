pub(crate) fn validate(config: &Config, v6: &Ipv6Config) -> Result<(), String> {
    if v6.provider_policy == crate::ProviderPolicy::ActiveStandby
        && (config.wan_backup.is_none()
            || v6.wan_mode != WanMode::Auto
            || v6.pd.is_none()
            || crate::wan::uplinks(config)
                .iter()
                .any(|w| w.mode == crate::WanProtocol::Static))
    {
        return Err(
            "active-standby IPv6 requires dual DHCP/PPPoE WAN, automatic IPv6 and PD".into(),
        );
    }
    if v6.wan_mode == WanMode::Auto && (v6.wan_address.is_some() || v6.wan_gateway.is_some()) {
        return Err("automatic IPv6 WAN cannot have a static address or gateway".into());
    }
    if let Some(pd) = &v6.pd {
        if v6.wan_mode != WanMode::Auto || !v6.lan_address.is_empty() || !v6.vlans.is_empty() {
            return Err("PD requires automatic WAN and no static LAN/VLAN IPv6 addresses".into());
        }
        if !(48..=64).contains(&pd.prefix_length) || pd.vlans.len() > 16 {
            return Err("PD requires a /48 through /64 hint and at most 16 VLANs".into());
        }
        let limit = 1u32 << (64 - pd.prefix_length);
        let mut ids = HashSet::from([pd.lan_subnet_id]);
        let mut names = HashSet::new();
        if pd.lan_subnet_id >= limit {
            return Err("LAN subnet ID does not fit requested delegation".into());
        }
        for vlan in &pd.vlans {
            if vlan.subnet_id >= limit
                || !ids.insert(vlan.subnet_id)
                || !names.insert(&vlan.interface)
                || !config.vlans.iter().any(|v| v.interface == vlan.interface)
            {
                return Err(
                    "PD VLAN requires a unique configured interface and unique in-range subnet ID"
                        .into(),
                );
            }
        }
    }
    Ok(())
}

pub fn targets(config: &Config) -> Vec<(String, u32, bool)> {
    let Some(pd) = config.ipv6.as_ref().and_then(|v| v.pd.as_ref()) else {
        return Vec::new();
    };
    let mut out = vec![(config.lan.interface.clone(), pd.lan_subnet_id, true)];
    out.extend(pd.vlans.iter().map(|v| {
        (
            v.interface.clone(),
            v.subnet_id,
            config
                .vlans
                .iter()
                .any(|other| other.interface == v.interface && other.internet),
        )
    }));
    out
}

pub fn render_client(config: &Config) -> Result<String, String> {
    render_client_for(config, config.wan.device())
}
pub fn render_client_for(config: &Config, device: &str) -> Result<String, String> {
    let Some(v6) = config.ipv6.as_ref().filter(|v| v.wan_mode == WanMode::Auto) else {
        return Ok(String::new());
    };
    let targets = targets(config);
    let interfaces = std::iter::once(device.to_string())
        .chain(targets.iter().map(|(name, _, _)| name.clone()))
        .collect::<Vec<_>>()
        .join(" ");
    let mut out=format!("# Generated by RouterTop; DHCPv4 remains owned by udhcpc.\nipv6only\nnoipv6rs\nnohook resolv.conf,hostname,ntp.conf,wpa_supplicant\nscript /usr/sbin/routertop-ipv6-hook\nallowinterfaces {interfaces}\nslaac hwaddr\ninterface {device}\n ipv6rs\n ia_na 1\n");
    if config.wan.mode == crate::WanProtocol::Pppoe {
        out = out.replace(" ipv6rs\n ia_na 1", " noipv6rs\n ia_na 1");
    }
    if let Some(pd) = &v6.pd {
        write!(out, " ia_pd 2/::/{}", pd.prefix_length).unwrap();
        for (name, id, _) in &targets {
            write!(out, " {name}/{id}/64/1").unwrap();
        }
        out.push('\n');
    }
    for (name, _, _) in targets {
        writeln!(out, "interface {name}\n noipv6rs\n nodhcp6").unwrap();
    }
    Ok(out)
}

pub(crate) fn render_lans(
    config: &Config,
    out: &mut Extra,
    destination: &str,
    egress: bool,
) -> Result<(), String> {
    for (index, (name, _, internet)) in targets(config).iter().enumerate() {
        writeln!(out.sets,"    set pd_net{index} {{ type ipv6_addr; flags interval,timeout; timeout 5s; }}\n    set pd_addr{index} {{ type ipv6_addr; flags timeout; timeout 5s; }}").unwrap();
        // Guards precede established and custom rules so old leases cannot
        // survive in conntrack, even if the reconciliation process stops.
        writeln!(out.guard,"        iifname \"{name}\" meta nfproto ipv6 ip6 saddr != @pd_net{index} drop\n        oifname \"{name}\" meta nfproto ipv6 ip6 daddr != @pd_net{index} drop").unwrap();
        writeln!(out.input,"        iifname \"{name}\" ip6 hoplimit 255 ip6 saddr {{ ::, fe80::/10 }} meta l4proto ipv6-icmp icmpv6 type nd-router-solicit accept\n        iifname \"{name}\" ip6 saddr @pd_net{index} ip6 daddr @pd_addr{index} udp dport 53 accept\n        iifname \"{name}\" ip6 saddr @pd_net{index} ip6 daddr @pd_addr{index} tcp dport 53 accept\n        iifname \"{name}\" ip6 saddr @pd_net{index} ip6 daddr @pd_addr{index} meta l4proto ipv6-icmp icmpv6 type echo-request accept").unwrap();
        writeln!(out.dnsmasq,"dhcp-range=set:rt6-{name},::,constructor:{name},ra-only,64,12h\ndhcp-option=tag:rt6-{name},option6:dns-server,[::]").unwrap();
        if !internet || !egress {
            writeln!(out.dnsmasq, "ra-param={name},5,0").unwrap();
        }
        if *internet && egress {
            writeln!(out.forward,"        iifname \"{name}\" oifname \"{destination}\" ip6 saddr @pd_net{index} accept").unwrap();
            if ipv6::full_tunnel(config).is_some_and(|wg| wg.nat66) {
                writeln!(
                    out.nat,
                    "        oifname \"{destination}\" ip6 saddr @pd_net{index} masquerade"
                )
                .unwrap();
            }
        }
    }
    Ok(())
}

#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct LeasePrefix {
    pub prefix: String,
    pub preferred_seconds: u64,
    pub valid_seconds: u64,
}
#[derive(Clone, Debug, Default, Serialize, Deserialize)]
pub struct Lease {
    pub acquired: u64,
    pub prefixes: Vec<LeasePrefix>,
    pub dns: Vec<String>,
    pub dns_lifetime: u64,
}
#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct Delegated {
    pub interface: String,
    pub address: String,
    pub prefix: String,
    pub preferred_seconds: u64,
    pub valid_seconds: u64,
}

/// Validate the actual delegation, not merely the requested size. A smaller
/// grant must never cause different subnet IDs to alias the same /64.
pub fn delegated(config: &Config, lease: &Lease, now: u64) -> Result<Vec<Delegated>, String> {
    let age = now.saturating_sub(lease.acquired);
    let mut out = Vec::new();
    for prefix in &lease.prefixes {
        if prefix.valid_seconds <= age {
            continue;
        }
        let net = ipv6::network(&prefix.prefix)?;
        if !(48..=64).contains(&net.prefix) || !ipv6::global_or_ula(net.first()) {
            return Err("invalid delegated prefix".into());
        }
        for (name, id, _) in targets(config) {
            if u64::from(id) >= 1u64 << (64 - net.prefix) {
                return Err("actual delegation is too small for configured subnet IDs".into());
            }
            let subnet = Net6 {
                ip: net.first() | (u128::from(id) << 64),
                prefix: 64,
            };
            for wg in &config.wireguard {
                if let Some(value) = &wg.address_v6 {
                    if subnet.overlaps(ipv6::host(value, 64, 128)?) {
                        return Err("delegation overlaps WireGuard interface".into());
                    }
                }
                for route in wg
                    .peers
                    .iter()
                    .flat_map(|p| &p.allowed_ips)
                    .filter(|s| s.contains(':') && *s != "::/0")
                {
                    if subnet.overlaps(ipv6::network(route)?) {
                        return Err("delegation overlaps WireGuard route".into());
                    }
                }
            }
            if out
                .iter()
                .any(|entry: &Delegated| entry.prefix == subnet.text())
            {
                return Err("delegated prefixes overlap".into());
            }
            out.push(Delegated {
                interface: name,
                address: format!("{}/64", Ipv6Addr::from(subnet.ip | 1)),
                prefix: subnet.text(),
                preferred_seconds: prefix.preferred_seconds.saturating_sub(age),
                valid_seconds: prefix.valid_seconds - age,
            });
        }
    }
    Ok(out)
}

pub fn lease_from_env(env: &BTreeMap<String, String>, now: u64) -> Result<Lease, String> {
    let mut lease = Lease {
        acquired: now,
        ..Lease::default()
    };
    let integer = |key: &str| -> Result<u64, String> {
        env.get(key)
            .ok_or_else(|| format!("missing {key}"))?
            .parse()
            .map_err(|_| format!("invalid {key}"))
    };
    for index in 1..=16 {
        let key = format!("new_dhcp6_ia_pd1_prefix{index}");
        // dhcpcd 10.5.2 puts the address in the indexed option itself;
        // only length and lifetimes have suffixes.
        let Some(value) = env.get(&key) else {
            continue;
        };
        let length = integer(&format!("{key}_length"))?;
        let prefix = format!("{value}/{length}");
        ipv6::network(&prefix)?;
        let valid = integer(&format!("{key}_vltime"))?;
        let preferred = integer(&format!("{key}_pltime"))?;
        if preferred > valid || valid > u64::from(u32::MAX) {
            return Err("invalid delegated lifetime".into());
        }
        lease.prefixes.push(LeasePrefix {
            prefix,
            valid_seconds: valid,
            preferred_seconds: preferred,
        });
    }
    lease.dns = valid_dns(
        env.get("new_dhcp6_name_servers")
            .map(String::as_str)
            .unwrap_or(""),
    );
    lease.dns_lifetime = lease
        .prefixes
        .iter()
        .filter(|p| p.valid_seconds > 0)
        .map(|p| p.valid_seconds)
        .min()
        .or_else(|| {
            env.get("new_dhcp6_ia_na1_ia_addr1_vltime")
                .and_then(|v| v.parse().ok())
        })
        .unwrap_or(0);
    Ok(lease)
}
fn valid_dns(value: &str) -> Vec<String> {
    value
        .split_whitespace()
        .filter_map(|s| s.parse::<Ipv6Addr>().ok())
        .filter(|ip| ipv6::global_or_ula(u128::from(*ip)))
        .map(|ip| ip.to_string())
        .take(8)
        .collect()
}
fn uptime() -> Result<u64, String> {
    fs::read_to_string("/proc/uptime")
        .map_err(|e| e.to_string())?
        .split_whitespace()
        .next()
        .ok_or("missing uptime")?
        .split('.')
        .next()
        .unwrap()
        .parse()
        .map_err(|_| "invalid uptime".into())
}
pub(crate) fn atomic(path: &Path, bytes: &[u8]) -> Result<(), String> {
    let temp = path.with_extension("tmp");
    let mut file = File::create(&temp).map_err(|e| e.to_string())?;
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        file.set_permissions(fs::Permissions::from_mode(
            if path.file_name().is_some_and(|v| v == "status.json") {
                0o644
            } else {
                0o600
            },
        ))
        .map_err(|e| e.to_string())?;
    }
    file.write_all(bytes).map_err(|e| e.to_string())?;
    fs::rename(temp, path).map_err(|e| e.to_string())
}
pub(crate) fn lock(dir: &Path) -> Result<File, String> {
    fs::create_dir_all(dir).map_err(|e| e.to_string())?;
    let file = OpenOptions::new()
        .create(true)
        .truncate(false)
        .read(true)
        .write(true)
        .open(dir.join("lock"))
        .map_err(|e| e.to_string())?;
    for _ in 0..250 {
        if file.try_lock_exclusive().is_ok() {
            return Ok(file);
        }
        thread::sleep(Duration::from_millis(20));
    }
    Err("PD lock timeout".into())
}
fn read_lease(path: &Path) -> Lease {
    fs::read(path)
        .ok()
        .and_then(|bytes| serde_json::from_slice(&bytes).ok())
        .unwrap_or_default()
}

pub fn event(config: &Config, dir: &Path, env: &BTreeMap<String, String>) -> Result<(), String> {
    let epoch = if crate::provider::enabled(config) {
        let current = crate::provider::read(dir)?;
        if !crate::provider::accepts(&current, env) {
            return Ok(());
        }
        Some(current)
    } else {
        None
    };
    let selected = epoch
        .as_ref()
        .map(|e| crate::provider::selected(config, e))
        .transpose()?;
    let config = selected.as_ref().unwrap_or(config);
    let device = epoch
        .as_ref()
        .map_or(config.wan.device(), |v| v.logical_interface.as_str());
    if !crate::provider::enabled(config)
        && config.wan_backup.is_some()
        && !crate::wan::primary_active(&dir.parent().ok_or("PD parent missing")?.join("wan"))
    {
        return Ok(());
    }
    if env.get("interface") != Some(&device.to_string()) {
        return Ok(());
    }
    let _lock = lock(dir)?;
    // Recheck after locking: a WAN transition may have withdrawn state while
    // this hook waited for a preceding reconciliation.
    if !crate::provider::enabled(config)
        && config.wan_backup.is_some()
        && !crate::wan::primary_active(&dir.parent().ok_or("PD parent missing")?.join("wan"))
    {
        return Ok(());
    }

    if let Some(epoch) = &epoch {
        if crate::provider::read(dir)? != *epoch {
            return Ok(());
        }
        atomic(&dir.join("lease-epoch"), epoch.token().as_bytes())?;
    }
    let now = uptime()?;
    let reason = env.get("reason").map(String::as_str).unwrap_or("");
    match reason {
        "BOUND6" | "RENEW6" | "REBIND6" | "REBOOT6" => {
            // Invalid updates remove the previous authorization rather than
            // keeping a formerly valid lease alive.
            let lease = lease_from_env(env, now);
            let stored = lease.as_ref().cloned().unwrap_or_default();
            atomic(
                &dir.join("lease.json"),
                &serde_json::to_vec(&stored).unwrap(),
            )?;
            if crate::provider::enabled(config) {
                if let Ok(ref lease) = lease {
                    let mut owned: Vec<Delegated> = fs::read(dir.join("owned-addresses.json"))
                        .ok()
                        .and_then(|b| serde_json::from_slice(&b).ok())
                        .unwrap_or_default();
                    owned.extend(delegated(config, lease, now)?);
                    owned.sort_by_key(|e| format!("{}:{}", e.interface, e.address));
                    owned.dedup_by(|a, b| a.interface == b.interface && a.address == b.address);
                    atomic(
                        &dir.join("owned-addresses.json"),
                        &serde_json::to_vec(&owned).unwrap(),
                    )?;
                }
            }
            lease.map(|_| ())
        }
        "EXPIRE6" | "RELEASE6" | "STOP6" | "STOPPED" | "NOCARRIER" | "NOCARRIER_ROAMING"
        | "DEPARTED" => {
            atomic(&dir.join("lease.json"), b"{}")?;
            atomic(&dir.join("ra-dns.json"), b"{}")
        }
        "ROUTERADVERT" => {
            let mut dns = Lease {
                acquired: now,
                ..Lease::default()
            };
            let mut min = u64::MAX;
            for i in 1..=8 {
                for j in 1..=8 {
                    let base = format!("nd{i}_rdnss{j}");
                    let remaining = env
                        .get(&format!("{base}_lifetime"))
                        .and_then(|v| v.parse::<u64>().ok())
                        .unwrap_or(0)
                        .saturating_sub(
                            env.get(&format!("nd{i}_now"))
                                .and_then(|v| v.parse::<u64>().ok())
                                .unwrap_or(0)
                                .saturating_sub(
                                    env.get(&format!("nd{i}_acquired"))
                                        .and_then(|v| v.parse::<u64>().ok())
                                        .unwrap_or(0),
                                ),
                        );
                    if remaining > 0 {
                        if let Some(value) = env.get(&format!("{base}_servers")) {
                            dns.dns.extend(valid_dns(value));
                            min = min.min(remaining);
                        }
                    }
                }
            }
            dns.dns.sort();
            dns.dns.dedup();
            dns.dns.truncate(8);
            dns.dns_lifetime = if min == u64::MAX { 0 } else { min };
            atomic(&dir.join("ra-dns.json"), &serde_json::to_vec(&dns).unwrap())
        }
        _ => Ok(()),
    }
}

fn output(program: &str, args: &[&str]) -> Result<Vec<u8>, String> {
    let output = Command::new("timeout")
        .arg("4")
        .arg(program)
        .args(args)
        .output()
        .map_err(|e| e.to_string())?;
    if !output.status.success() {
        return Err(format!(
            "{program} failed: {}",
            String::from_utf8_lossy(&output.stderr)
        ));
    }
    Ok(output.stdout)
}
pub(crate) fn nft(script: &str) -> Result<(), String> {
    let mut child = Command::new("timeout")
        .args(["4", "nft", "-f", "-"])
        .stdin(Stdio::piped())
        .spawn()
        .map_err(|e| e.to_string())?;
    child
        .stdin
        .take()
        .ok_or("nft stdin missing")?
        .write_all(script.as_bytes())
        .map_err(|e| e.to_string())?;
    if !child.wait().map_err(|e| e.to_string())?.success() {
        return Err("dynamic firewall update failed".into());
    }
    Ok(())
}

/// One atomic nft transaction refreshes only our delegated sets. Timeout
/// elements expire within five seconds if the monitor crashes or is killed.
pub fn set_update(config: &Config, delegated: &[Delegated]) -> String {
    let mut script = String::new();
    for (index, (name, _, _)) in targets(config).iter().enumerate() {
        writeln!(
            script,
            "flush set inet routertop pd_net{index}\nflush set inet routertop pd_addr{index}"
        )
        .unwrap();
        for entry in delegated
            .iter()
            .filter(|e| e.interface == *name && e.valid_seconds > 0)
        {
            let timeout = entry.valid_seconds.min(5);
            writeln!(script,"add element inet routertop pd_net{index} {{ {} timeout {timeout}s }}\nadd element inet routertop pd_addr{index} {{ {} timeout {timeout}s }}",entry.prefix,entry.address.split('/').next().unwrap()).unwrap();
        }
    }
    script
}

fn wan_update(_config: &Config, device: &str, online: bool) -> String {
    let mut text = "flush set inet routertop auto_wan\n".to_string();
    if online {
        writeln!(
            text,
            "add element inet routertop auto_wan {{ \"{}\" timeout 5s }}",
            device
        )
        .unwrap();
    }
    text
}

pub(crate) fn withdraw_previous(dir: &Path, keep: &[Delegated]) -> Result<(), String> {
    let status: Value = fs::read(dir.join("status.json"))
        .ok()
        .and_then(|bytes| serde_json::from_slice(&bytes).ok())
        .unwrap_or(Value::Null);
    for old in status["delegated"].as_array().into_iter().flatten() {
        let Some(name) = old["interface"].as_str() else {
            continue;
        };
        let Some(address) = old["address"].as_str() else {
            continue;
        };
        if keep
            .iter()
            .any(|new| new.interface == name && new.address == address)
        {
            continue;
        }
        // Kernel lifetime change lets dnsmasq send a deprecating/withdrawing
        // constructor advertisement; removal follows within two seconds.
        let _ = output(
            "ip",
            &[
                "-6",
                "address",
                "change",
                address,
                "dev",
                name,
                "preferred_lft",
                "0",
                "valid_lft",
                "2",
            ],
        );
    }
    Ok(())
}

fn ra_config(config: &Config, online: bool) -> String {
    let Some(v6) = &config.ipv6 else {
        return String::new();
    };
    let egress = ipv6::full_tunnel(config).is_none_or(ipv6::full_v6);
    if !egress {
        return String::new();
    }
    let names = if v6.pd.is_some() {
        targets(config)
            .into_iter()
            .filter(|(_, _, internet)| *internet)
            .map(|(name, _, _)| name)
            .collect::<Vec<_>>()
    } else {
        std::iter::once(config.lan.interface.clone())
            .chain(
                v6.vlans
                    .iter()
                    .filter(|v| {
                        config
                            .vlans
                            .iter()
                            .any(|other| other.interface == v.interface && other.internet)
                    })
                    .map(|v| v.interface.clone()),
            )
            .collect()
    };
    names
        .into_iter()
        .map(|name| format!("ra-param={name},5,{}\n", if online { 30 } else { 0 }))
        .collect()
}

pub(crate) fn update_ra(config: &Config, dir: &Path, online: bool) -> Result<(), String> {
    let ra = ra_config(config, online);
    if fs::read_to_string(dir.join("ra.conf")).unwrap_or_default() != ra {
        atomic(&dir.join("ra.conf"), ra.as_bytes())?;
        // SIGHUP does not reload ra-param. A fixed supervisor restarts the
        // owned dnsmasq only on state changes, never every invalid lease poll.
        atomic(&dir.join("dnsmasq-restart"), b"changed")?;
    }
    Ok(())
}

pub(crate) fn identity(identity: &Path) -> Result<String, String> {
    if !identity.exists() {
        fs::create_dir_all(identity.parent().ok_or("identity parent missing")?)
            .map_err(|e| e.to_string())?;
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            fs::set_permissions(
                identity.parent().unwrap(),
                fs::Permissions::from_mode(0o700),
            )
            .map_err(|e| e.to_string())?;
        }
        let mut bytes = [0u8; 16];
        rand_core::RngCore::try_fill_bytes(&mut rand_core::OsRng, &mut bytes)
            .map_err(|e| e.to_string())?;
        let value = format!(
            "00:04:{}",
            bytes
                .iter()
                .map(|b| format!("{b:02x}"))
                .collect::<Vec<_>>()
                .join(":")
        );
        let mut options = OpenOptions::new();
        options.write(true).create_new(true);
        #[cfg(unix)]
        {
            use std::os::unix::fs::OpenOptionsExt;
            options.mode(0o600);
        }
        let mut file = options.open(identity).map_err(|e| e.to_string())?;
        file.write_all(value.as_bytes())
            .map_err(|e| e.to_string())?;
        file.sync_all().map_err(|e| e.to_string())?;
        #[cfg(unix)]
        File::open(identity.parent().unwrap())
            .and_then(|parent| parent.sync_all())
            .map_err(|e| e.to_string())?;
    }
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        fs::set_permissions(identity, fs::Permissions::from_mode(0o600))
            .map_err(|e| e.to_string())?;
        fs::set_permissions(
            identity.parent().unwrap(),
            fs::Permissions::from_mode(0o700),
        )
        .map_err(|e| e.to_string())?;
    }
    let duid = fs::read_to_string(identity).map_err(|e| e.to_string())?;
    if duid.len() != 53
        || !duid.starts_with("00:04:")
        || duid
            .split(':')
            .any(|s| s.len() != 2 || !s.bytes().all(|b| b.is_ascii_hexdigit()))
    {
        return Err("invalid persistent DHCPv6 identity; refusing reset".into());
    }
    Ok(duid)
}

pub fn initialize(config: &Config, dir: &Path, identity: &Path) -> Result<(), String> {
    initialize_for(config, dir, identity, config.wan.device())
}
pub(crate) fn initialize_for(
    config: &Config,
    dir: &Path,
    identity_path: &Path,
    device: &str,
) -> Result<(), String> {
    let _lock = lock(dir)?;
    let duid = identity(identity_path)?;
    atomic(
        &dir.join("identity-path"),
        identity_path.to_string_lossy().as_bytes(),
    )?;
    // Global directive must precede per-interface blocks.
    atomic(
        &dir.join("dhcpcd.conf"),
        format!("duid {duid}\n{}", render_client_for(config, device)?).as_bytes(),
    )?;
    atomic(&dir.join("ra.conf"), ra_config(config, false).as_bytes())?;
    atomic(&dir.join("resolv.conf"), b"")?;
    atomic(&dir.join("lease.json"), b"{}")?;
    atomic(&dir.join("ra-dns.json"), b"{}")?;
    // Never expose a previous initialization's status while reacquiring.
    atomic(&dir.join("status.json"), b"null")?;
    Ok(())
}

pub fn monitor(config: &Config, dir: &Path) -> Result<(), String> {
    let v6 = config
        .ipv6
        .as_ref()
        .filter(|v| v.wan_mode == WanMode::Auto)
        .ok_or("automatic IPv6 is not configured")?;
    loop {
        let _ = v6;
        let origin = if crate::provider::enabled(config) {
            crate::provider::read(dir).ok()
        } else {
            None
        };
        let result = reconcile_once(config, dir);
        if let Err(error) = result {
            let _guard = lock(dir)?;
            if crate::provider::enabled(config) && crate::provider::read(dir).ok() != origin {
                continue;
            }
            let mut closed =
                set_update(config, &[]) + &wan_update(config, config.wan.device(), false);
            if crate::provider::enabled(config) {
                closed.push_str("flush set inet routertop auto_sources\n");
            }
            let _ = nft(&closed);
            let _ = withdraw_previous(dir, &[]);
            let _ = atomic(&dir.join("resolv.conf"), b"");
            let _ = update_ra(config, dir, false);
            let _=atomic(&dir.join("status.json"),&serde_json::to_vec(&json!({"wan_mode":"auto","state":"degraded","phase":"degraded","provider":origin.as_ref().and_then(|e|e.provider()),"generation":origin.as_ref().map_or(0,|e|e.generation),"logical_interface":origin.as_ref().map(|e|e.logical_interface.clone()),"wan_addresses":[],"delegated":[],"dns_servers":[],"updated_uptime_seconds":uptime().unwrap_or(0),"error":error})).unwrap());
            eprintln!("IPv6 monitor: {error}");
        }
        thread::sleep(Duration::from_secs(1));
    }
}

pub fn reconcile_once(config: &Config, dir: &Path) -> Result<(), String> {
    let epoch = if crate::provider::enabled(config) {
        Some(crate::provider::read(dir)?)
    } else {
        None
    };
    if epoch.as_ref().is_some_and(|e| e.slot.is_none()) {
        return Ok(());
    }
    let selected;
    let config = if let Some(e) = &epoch {
        selected = crate::provider::selected(config, e)?;
        &selected
    } else {
        config
    };
    let device = epoch
        .as_ref()
        .map_or(config.wan.device(), |e| e.logical_interface.as_str());
    let v6 = config.ipv6.as_ref().ok_or("IPv6 absent")?;
    if !crate::provider::enabled(config)
        && config.wan_backup.is_some()
        && !crate::wan::primary_active(&dir.parent().ok_or("PD parent missing")?.join("wan"))
    {
        return disconnect(config, dir);
    }
    let bytes = output("ip", &["-j", "-6", "address", "show"])?;
    let devices: Vec<Value> = serde_json::from_slice(&bytes).map_err(|e| e.to_string())?;
    let routes: Vec<Value> = if devices.iter().any(|dev| dev["ifname"] == device) {
        serde_json::from_slice(&output(
            "ip",
            &["-j", "-6", "route", "show", "default", "dev", device],
        )?)
        .map_err(|e| e.to_string())?
    } else {
        Vec::new()
    };
    let _lock = lock(dir)?;
    if !crate::provider::enabled(config)
        && config.wan_backup.is_some()
        && !crate::wan::primary_active(&dir.parent().ok_or("PD parent missing")?.join("wan"))
    {
        drop(_lock);
        return disconnect(config, dir);
    }

    if let Some(epoch) = &epoch {
        if crate::provider::read(dir)? != *epoch {
            return Ok(());
        }
    }
    let now = uptime()?;
    let carrier = devices
        .iter()
        .find(|dev| dev["ifname"] == device)
        .is_some_and(|dev| {
            dev["flags"]
                .as_array()
                .is_some_and(|flags| flags.iter().any(|flag| flag == "LOWER_UP"))
        });
    let online = carrier && routes.iter().any(|r| r["type"] != "unreachable");
    let lease = if epoch.as_ref().is_none_or(|e| {
        fs::read_to_string(dir.join("lease-epoch")).ok().as_deref() == Some(e.token().as_str())
    }) {
        read_lease(&dir.join("lease.json"))
    } else {
        Lease::default()
    };
    let mut entries = if online {
        delegated(config, &lease, now)?
    } else {
        Vec::new()
    };
    let mut wan_addresses = Vec::new();
    let mut wan_nets = Vec::new();
    for dev in &devices {
        if dev["ifname"] != device {
            continue;
        }
        for address in dev["addr_info"].as_array().into_iter().flatten() {
            if address["tentative"] == true || address["dadfailed"] == true {
                continue;
            }
            if let (Some(ip), Some(prefix)) =
                (address["local"].as_str(), address["prefixlen"].as_u64())
            {
                let value = format!("{ip}/{prefix}");
                if let Ok(net) = ipv6::host(&value, 1, 128) {
                    wan_nets.push(net);
                    wan_addresses.push(value);
                }
            }
        }
    }
    if entries.iter().any(|entry| {
        ipv6::network(&entry.prefix).is_ok_and(|net| wan_nets.iter().any(|wan| net.overlaps(*wan)))
    }) {
        return Err("delegation overlaps connected WAN".into());
    }
    for wan in &wan_nets {
        for wg in &config.wireguard {
            if wg
                .address_v6
                .as_ref()
                .is_some_and(|s| ipv6::host(s, 64, 128).is_ok_and(|net| wan.overlaps(net)))
            {
                return Err("dynamic WAN overlaps WireGuard interface".into());
            }
            for route in wg
                .peers
                .iter()
                .flat_map(|p| &p.allowed_ips)
                .filter(|s| s.contains(':') && *s != "::/0")
            {
                if wan.overlaps(ipv6::network(route)?) {
                    return Err("dynamic WAN overlaps WireGuard route".into());
                }
            }
        }
        if v6.pd.is_none() {
            for value in std::iter::once(&v6.lan_address).chain(v6.vlans.iter().map(|v| &v.address))
            {
                if wan.overlaps(ipv6::host(value, 64, 64)?) {
                    return Err("dynamic WAN overlaps static LAN/VLAN".into());
                }
            }
        }
    }
    withdraw_previous(dir, &entries)?;
    entries.retain_mut(|entry| {
        let Some(address) = devices
            .iter()
            .find(|dev| dev["ifname"] == entry.interface)
            .and_then(|dev| dev["addr_info"].as_array())
            .and_then(|addresses| {
                addresses.iter().find(|addr| {
                    format!(
                        "{}/{}",
                        addr["local"].as_str().unwrap_or(""),
                        addr["prefixlen"]
                    ) == entry.address
                })
            })
        else {
            return false;
        };
        if address["tentative"] == true || address["dadfailed"] == true {
            return false;
        }
        entry.valid_seconds = entry
            .valid_seconds
            .min(address["valid_life_time"].as_u64().unwrap_or(0));
        entry.preferred_seconds = entry
            .preferred_seconds
            .min(address["preferred_life_time"].as_u64().unwrap_or(0));
        entry.valid_seconds > 0
    });
    let mut authorization = set_update(config, &entries)
        + &wan_update(
            config,
            device,
            online && (v6.pd.is_none() || !entries.is_empty()),
        );
    if crate::provider::enabled(config) {
        authorization.push_str("flush set inet routertop auto_sources\n");
        if online && !entries.is_empty() {
            for source in entries.iter().map(|e| e.prefix.clone()).chain(
                wan_addresses
                    .iter()
                    .map(|s| format!("{}/128", s.split('/').next().unwrap())),
            ) {
                writeln!(
                    authorization,
                    "add element inet routertop auto_sources {{ {source} timeout 5s }}"
                )
                .unwrap();
            }
        }
    }
    nft(&authorization)?;
    let mut dns = Vec::new();
    if online && v6.dns_auto && ipv6::full_tunnel(config).is_none() {
        for source in [&lease, &read_lease(&dir.join("ra-dns.json"))] {
            if now.saturating_sub(source.acquired) < source.dns_lifetime {
                dns.extend(source.dns.clone());
            }
        }
    }
    dns.retain(|server| {
        !devices
            .iter()
            .flat_map(|dev| dev["addr_info"].as_array().into_iter().flatten())
            .any(|addr| addr["local"] == *server)
    });
    dns.sort();
    dns.dedup();
    dns.truncate(8);
    atomic(
        &dir.join("resolv.conf"),
        dns.iter()
            .map(|ip| format!("nameserver {ip}\n"))
            .collect::<String>()
            .as_bytes(),
    )?;
    update_ra(
        config,
        dir,
        online && (v6.pd.is_none() || !entries.is_empty()),
    )?;
    let state = if online && (v6.pd.is_none() || !entries.is_empty()) {
        "bound"
    } else {
        "waiting"
    };
    atomic(&dir.join("status.json"),&serde_json::to_vec(&json!({"wan_mode":"auto","state":state,"wan_addresses":wan_addresses,"delegated":entries,"dns_servers":dns,"updated_uptime_seconds":now,"error":null,"provider":epoch.as_ref().and_then(|e|e.provider()),"generation":epoch.as_ref().map_or(0,|e|e.generation),"logical_interface":device,"phase":if state=="bound"{"bound"}else{"acquiring"}})).unwrap())
}

pub fn read_status() -> Value {
    status_at(Path::new("/run/routertop/pd"))
}
pub fn status_at(dir: &Path) -> Value {
    fs::read(dir.join("status.json"))
        .ok()
        .and_then(|bytes| serde_json::from_slice::<Value>(&bytes).ok())
        .filter(|v| {
            uptime().is_ok_and(|now| {
                v["updated_uptime_seconds"]
                    .as_u64()
                    .is_some_and(|then| now.saturating_sub(then) <= 10)
            })
        })
        .unwrap_or(Value::Null)
}

/// A negotiated PPP session was lost. Remove authorization immediately rather
/// than waiting for the old DHCPv6 grant's remaining lifetime.
pub fn disconnect(config: &Config, dir: &Path) -> Result<(), String> {
    let _guard = lock(dir)?;
    atomic(&dir.join("lease.json"), b"{}")?;
    atomic(&dir.join("ra-dns.json"), b"{}")?;
    nft(&(set_update(config, &[]) + &wan_update(config, config.wan.device(), false)))?;
    withdraw_previous(dir, &[])?;
    atomic(&dir.join("resolv.conf"), b"")?;
    update_ra(config, dir, false)?;
    atomic(&dir.join("status.json"),br#"{"wan_mode":"auto","state":"waiting","wan_addresses":[],"delegated":[],"dns_servers":[],"error":null}"#)
}

